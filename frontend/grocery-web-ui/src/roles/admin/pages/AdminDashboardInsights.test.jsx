import { screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import { insightReport } from '../../../test/aiFixtures'
import { mockApi, problem } from '../../../test/mockApi'
import { renderApp } from '../../../test/renderApp'
import { signInAs } from '../../../test/session'

describe('Admin dashboard — AI insights', () => {
  it('generates the structured report on request', async () => {
    const user = userEvent.setup()
    signInAs(['OPS_ADMIN'])
    const api = mockApi({ 'POST /ai/agents/admin-bi/insights': { status: 200, data: insightReport() } })
    renderApp('/admin')

    const card = await screen.findByRole('region', { name: 'AI insights' })
    expect(card).toHaveTextContent('Nothing generated yet.')
    expect(api.callsTo('POST /ai/agents/admin-bi/insights')).toHaveLength(0)

    await user.click(within(card).getByRole('button', { name: 'Generate' }))

    expect(
      await within(card).findByRole('heading', { name: 'Orders are up; two orders are stuck at the store' }),
    ).toBeInTheDocument()
    expect(card).toHaveTextContent(/Fri, 13 Nov,? 2026/)
    expect(within(card).getByText('Orders').nextElementSibling).toHaveTextContent('42')
    expect(card).toHaveTextContent('+12% on yesterday')
    expect(within(card).getByText('Confirmed revenue').nextElementSibling).toHaveTextContent('₹10,250')
    expect(within(within(card).getByRole('region', { name: 'Observations' })).getByRole('listitem')).toHaveTextContent(
      'Most orders came from Green Basket.',
    )
    expect(within(within(card).getByRole('region', { name: 'Risks' })).getByRole('listitem')).toHaveTextContent(
      '2 orders are waiting for the store for over an hour.',
    )
    expect(
      within(within(card).getByRole('region', { name: 'Suggested actions' })).getByRole('listitem'),
    ).toHaveTextContent('Call Green Basket about GA-7K3F9Q2M.')
    expect(card).toHaveTextContent('Generated by ollama · qwen3:4b')
    expect(within(card).queryByText('Rules fallback')).not.toBeInTheDocument()
    expect(api.callsTo('POST /ai/agents/admin-bi/insights')[0]?.body).toEqual({})
    expect(within(card).getByRole('button', { name: 'Generate again' })).toBeEnabled()
  })

  it('labels the rule-based fallback (model unavailable)', async () => {
    const user = userEvent.setup()
    signInAs(['FINANCE_ADMIN'])
    mockApi({
      'POST /ai/agents/admin-bi/insights': {
        status: 200,
        data: insightReport({ headline: '42 orders today; 2 stuck', generatedBy: { provider: 'rules', model: null } }),
      },
    })
    renderApp('/admin')
    const card = await screen.findByRole('region', { name: 'AI insights' })
    await user.click(within(card).getByRole('button', { name: 'Generate' }))

    expect(await within(card).findByRole('heading', { name: '42 orders today; 2 stuck' })).toBeInTheDocument()
    expect(within(card).getByText('Rules fallback')).toBeInTheDocument()
    expect(card).toHaveTextContent('Generated by rules from the same data: the AI model was not available.')
  })

  it('shows a failure with a retry', async () => {
    const user = userEvent.setup()
    signInAs(['SUPPORT'])
    let calls = 0
    mockApi({
      'POST /ai/agents/admin-bi/insights': () => {
        calls++
        return calls === 1
          ? problem(503, 'SERVICE_UNAVAILABLE', 'The assistant service is down')
          : { status: 200, data: insightReport() }
      },
    })
    renderApp('/admin')
    const card = await screen.findByRole('region', { name: 'AI insights' })
    await user.click(within(card).getByRole('button', { name: 'Generate' }))

    const alert = await within(card).findByRole('alert')
    expect(alert).toHaveTextContent('Could not generate insights')
    expect(alert).toHaveTextContent('The assistant service is down')
    await user.click(within(alert).getByRole('button', { name: 'Try again' }))
    expect(
      await within(card).findByRole('heading', { name: 'Orders are up; two orders are stuck at the store' }),
    ).toBeInTheDocument()
  })
})
