import { useId } from 'react'
import { Link } from 'react-router'
import { ApiError } from '../../shared/api/problemDetail'
import { Badge, Button, ErrorState, Spinner } from '../../shared/components/ui'
import { Icon } from '../../shared/icons'
import { formatDateTime } from '../../shared/utils/format'
import { formatLongDay } from '../../shared/utils/indiaDate'
import { type InsightReport, RULES_PROVIDER } from './api'
import { useGenerateInsights } from './hooks'

function ReportList({ title, items, tone }: { title: string; items: readonly string[]; tone: 'neutral' | 'risk' | 'action' }) {
  const titleId = useId()
  if (items.length === 0) return null
  const marker = tone === 'risk' ? 'marker:text-amber-500' : tone === 'action' ? 'marker:text-emerald-600' : 'marker:text-slate-400'
  return (
    <section aria-labelledby={titleId}>
      <h4 id={titleId} className="text-xs font-semibold tracking-wide text-slate-500 uppercase">
        {title}
      </h4>
      <ul className={`mt-1 list-disc space-y-1 pl-5 text-sm text-slate-700 ${marker}`}>
        {items.map((item, index) => (
          <li key={index} className="break-words">
            {item}
          </li>
        ))}
      </ul>
    </section>
  )
}

function GeneratedBy({ report }: { report: InsightReport }) {
  const rules = report.generatedBy.provider === RULES_PROVIDER
  return (
    <p className="flex flex-wrap items-center gap-2 border-t border-slate-100 pt-3 text-xs text-slate-500">
      {rules ? (
        <>
          <Badge tone="amber">Rules fallback</Badge>
          <span>Generated by rules from the same data: the AI model was not available.</span>
        </>
      ) : (
        <span>
          Generated by {report.generatedBy.provider}
          {report.generatedBy.model ? ` · ${report.generatedBy.model}` : ''}
        </span>
      )}
      <span>· {formatDateTime(report.generatedAt)}</span>
    </p>
  )
}

function Report({ report }: { report: InsightReport }) {
  return (
    <div className="space-y-4" aria-label="Insight report" role="group">
      <div>
        <p className="text-xs text-slate-500">{formatLongDay(report.date)}</p>
        <h3 className="mt-0.5 text-base font-semibold text-slate-900">{report.headline}</h3>
      </div>
      {report.kpis.length > 0 && (
        <dl className="grid grid-cols-2 gap-3 sm:grid-cols-4">
          {report.kpis.map((kpi, index) => (
            <div key={`${kpi.name}-${index}`} className="flex flex-col-reverse rounded-lg bg-slate-50 px-3 py-2">
              <dt className="text-xs font-medium text-slate-500">
                {kpi.name}
                {kpi.note && <span className="block font-normal text-slate-400">{kpi.note}</span>}
              </dt>
              <dd className="text-lg font-bold text-slate-900 tabular-nums">{String(kpi.value)}</dd>
            </div>
          ))}
        </dl>
      )}
      <div className="grid gap-4 md:grid-cols-3">
        <ReportList title="Observations" items={report.observations} tone="neutral" />
        <ReportList title="Risks" items={report.risks} tone="risk" />
        <ReportList title="Suggested actions" items={report.suggestedActions} tone="action" />
      </div>
      <GeneratedBy report={report} />
    </div>
  )
}

/**
 * Admin dashboard (Phase 11 §6): "AI insights" — on request, the server collects today's stats, stuck orders and
 * reconciliation with the admin's rights and asks the model for a typed report; without a model the same data is
 * summarised by rules (labelled as such).
 */
export function InsightsCard() {
  const titleId = useId()
  const generate = useGenerateInsights()
  const report = generate.data

  return (
    <section aria-labelledby={titleId} className="rounded-2xl border border-slate-200/70 bg-white p-5 shadow-sm">
      <header className="mb-4 flex flex-wrap items-start justify-between gap-3">
        <div className="min-w-0">
          <h2 id={titleId} className="flex items-center gap-2 text-base font-semibold text-slate-900">
            <Icon name="sparkle" className="size-5" />
            AI insights
          </h2>
          <p className="mt-1 text-sm text-slate-500">
            Today’s orders, stuck orders and payment reconciliation, read and summarised by the business assistant.
          </p>
        </div>
        <Button variant={report ? 'secondary' : 'primary'} onClick={() => generate.mutate(undefined)} disabled={generate.isPending}>
          {generate.isPending && <Spinner size="sm" className={report ? undefined : '[&_svg]:text-white'} />}
          {report ? 'Generate again' : 'Generate'}
        </Button>
      </header>

      {generate.isPending && !report && (
        <p className="flex items-center gap-2 text-sm text-slate-500" role="status">
          <Spinner size="sm" /> Reading today’s data… a local model can take a minute.
        </p>
      )}
      {generate.isError && (
        <ErrorState
          title="Could not generate insights"
          message={generate.error.message}
          correlationId={generate.error instanceof ApiError ? generate.error.correlationId : null}
          onRetry={() => generate.mutate(undefined)}
        />
      )}
      {report && <Report report={report} />}
      {!report && !generate.isPending && !generate.isError && (
        <p className="text-sm text-slate-500">
          Nothing generated yet. Refunds, cancellations and suspensions the assistant proposes wait in{' '}
          <Link to="/admin/ai/approvals" className="font-medium text-emerald-700 hover:text-emerald-800">
            AI approvals
          </Link>
          .
        </p>
      )}
    </section>
  )
}
